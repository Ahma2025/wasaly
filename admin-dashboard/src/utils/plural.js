const forms = (key) => (Array.isArray(key) ? key : W[key]) || [key, key, key, key, key];

/** عبارة كاملة: arCount(3, 'restaurant') → «3 مطاعم» · zero: نص بديل لحالة الصفر */
export function arCount(n, key, { zero } = {}) {
  const c = Math.abs(Math.trunc(Number(n) || 0));
  const [s, one, two, few, many] = forms(key);
  if (c === 0) return zero ?? `لا ${few}`;
  if (c === 1) return one;
  if (c === 2) return two;
  const mod = c % 100;
  if (mod >= 3 && mod <= 10) return `${c} ${few}`;
  if (mod === 1 || mod === 2 || mod === 0) return `${c} ${s}`; // 101 طلب · 100 طلب
  return `${c} ${many}`;
}

/** الاسم وحده بعد رقم معروض بشكل منفصل (مثلاً رقم كبير ثم الوحدة): 1 طلب · 2 طلبين · 5 طلبات · 12 طلباً */
export function arUnit(n, key) {
  const c = Math.abs(Math.trunc(Number(n) || 0));
  const [s, , two, few, many] = forms(key);
  if (c === 2) return two;
  const mod = c % 100;
  if (mod >= 3 && mod <= 10) return few;
  if (c === 0 || mod === 0 || mod === 1 || mod === 2) return s;
  return many;
}

/** «2 من 3 مطاعم» آمن: يخفي «x من n» عندما x > n (X-05) */
export const ofTotal = (x, n) => {
  const a = parseInt(x) || 0, b = parseInt(n) || 0;
  return a > 0 && b > 0 && a <= b ? { x: a, n: b } : null;
};
